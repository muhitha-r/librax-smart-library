async function seedEngineeringBooks() {
  try {
    const uri = process.env.MONGODB_URI || process.env.MONGO_URI;
    if (!uri) {
      console.error('Error: MONGODB_URI or MONGO_URI is not set in environment variables.');
      process.exit(1);
    }

    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(uri);
    console.log('Connected successfully to MongoDB Atlas.');

    // 1. Verify that all 120 entries have unique ISBNs and correct counts
    const allBooks = [...engineeringBooks, ...extraBooks];
    if (allBooks.length !== 120) {
      throw new Error(`Expected exactly 120 books, got ${allBooks.length}`);
    }

    const isbnSet = new Set();
    const categoriesCount = {};

    for (const book of allBooks) {
      if (isbnSet.has(book.ISBN)) {
        throw new Error(`Duplicate ISBN detected in seed data: ${book.ISBN} ("${book.title}")`);
      }
      isbnSet.add(book.ISBN);
      categoriesCount[book.category] = (categoriesCount[book.category] || 0) + 1;

      if (book.availableCopies > book.totalCopies) {
        throw new Error(`Available copies exceeds total for ${book.title}`);
      }
      if (book.totalCopies < 3 || book.totalCopies > 10) {
        throw new Error(`Total copies out of bounds (3-10) for ${book.title}: ${book.totalCopies}`);
      }
    }

    console.log('\nVerified Branch Counts:');
    for (const [cat, count] of Object.entries(categoriesCount)) {
      console.log(`  - ${cat}: ${count} books`);
    }

    // 2. Clean Existing Duplicate Books & Test Dummy Entries
    console.log('\nCleaning test, duplicate, and non-engineering books...');
    
    // Purge existing books
    const deleteResult = await Book.deleteMany({});
    console.log(`Purged ${deleteResult.deletedCount} old catalog entries.`);

    // Clean up orphaned records in BorrowRecords, Reservations, and Wishlist
    const activeBooks = []; // temporarily empty before seeding
    const borrowClean = await BorrowRecord.deleteMany({ book: { $nin: activeBooks } });
    console.log(`Safely purged ${borrowClean.deletedCount} legacy test borrow records.`);

    const resClean = await Reservation.deleteMany({ book: { $nin: activeBooks } });
    console.log(`Safely purged ${resClean.deletedCount} legacy test reservations.`);

    const wishClean = await Wishlist.deleteMany({ book: { $nin: activeBooks } });
    console.log(`Safely purged ${wishClean.deletedCount} legacy wishlist records.`);

    // 3. Ensure Unique ISBN Index is created and active on Book collection
    console.log('\nSyncing unique indexes on Book collection...');
    await Book.syncIndexes();
    console.log('Indexes synced successfully on MongoDB Atlas.');

    // 4. Seed all 120 authentic textbooks
    console.log('\nInserting 120 unique textbooks...');
    const inserted = await Book.insertMany(allBooks);
    console.log(`Successfully seeded ${inserted.length} textbooks into MongoDB Atlas!`);

    // 5. Final Verification
    const finalCount = await Book.countDocuments();
    const finalCategories = await Book.distinct('category');
    console.log(`\nFinal Book Count in Atlas: ${finalCount}`);
    console.log('Distinct Categories in Atlas:', finalCategories.sort());

    await mongoose.disconnect();
    console.log('\nSeed script finished successfully with zero errors.');
    process.exit(0);
  } catch (error) {
    console.error('\nSeed script failed with error:', error);
    process.exit(1);
  }
}

seedEngineeringBooks();
